-- Skema inti universal untuk database nextlumen_db.
-- Disalin dari pola referensi (tabel CP*, SP login/reload) dengan penamaan universal:
--   dbo.app_encrypt/app_decrypt (fungsi enkripsi password)
--   tanpa referensi modul lama.

CREATE TABLE dbo.CPUSER (
    USERID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    USERLOGIN VARCHAR(25) NOT NULL,
    USERNAME VARCHAR(35) NULL,
    USERPASSWORD NVARCHAR(MAX) NULL,
    USERGROUP VARCHAR(25) NULL,
    USERLASTLOGIN DATETIME2 NULL,
    USERACTIVE VARCHAR(25) NULL,
    USEREMAIL VARCHAR(50) NULL,
    USERDEPT VARCHAR(25) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL,
    BTAPPROVE VARCHAR(10) NULL,
    GROUPMODEL VARCHAR(50) NULL
);

CREATE TABLE dbo.CPMATRIX (
    DEFID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    DEFMODULE VARCHAR(20) NULL,
    DEFCODE VARCHAR(200) NULL,
    DEFNAME VARCHAR(200) NULL,
    DEFSHORT NUMERIC(18,0) NULL,
    DEFVAL1 VARCHAR(50) NULL,
    DEFVAL2 VARCHAR(50) NULL,
    DEFIMAGE VARCHAR(100) NULL,
    DEFDESCRIPTION VARCHAR(200) NULL,
    DEFTOOLTIP VARCHAR(200) NULL,
    SYSCREATEUSER VARCHAR(35) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(35) NULL,
    SYSUPDATEDATE DATETIME2 NULL,
    DEFVAL3 VARCHAR(50) NULL,
    DEFVAL4 VARCHAR(50) NULL,
    DEFVAL5 VARCHAR(50) NULL,
    DEFNUM1 NUMERIC(18,2) NULL,
    DEFNUM2 NUMERIC(18,2) NULL,
    DEFNUM3 NUMERIC(18,2) NULL,
    DEFNUM4 NUMERIC(18,2) NULL,
    DEFNUM5 NUMERIC(18,2) NULL
);

CREATE TABLE dbo.CPMENU (
    MENUID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MCODE NUMERIC(18,0) NULL,
    MPARRENT NUMERIC(18,0) NULL,
    MMODULE VARCHAR(40) NULL,
    MNAME VARCHAR(40) NULL,
    MCONTROL VARCHAR(25) NULL,
    MCHILDREN VARCHAR(5) NULL,
    MEXPAND VARCHAR(5) NULL,
    MLEAF VARCHAR(5) NULL,
    MSHORT NUMERIC(18,0) NULL,
    MLOCKADMIN VARCHAR(5) NULL,
    MQTIP VARCHAR(200) NULL,
    MALLOWCLICK VARCHAR(5) NULL
);

CREATE TABLE dbo.CPMENUACCESS (
    GID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    RGROUP VARCHAR(20) NULL,
    RMODULE VARCHAR(20) NULL,
    RMENUID NUMERIC(18,0) NULL,
    ACCREATE VARCHAR(6) NULL,
    ACUPDATE VARCHAR(6) NULL,
    ACDELETE VARCHAR(6) NULL,
    ACDATAALL VARCHAR(6) NULL
);
