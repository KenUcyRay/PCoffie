-- Kampanye iklan (Marketing Tools, module Marketing). Aturan: T_ prefix.
-- Satu baris = satu kampanye. Tarif/hari disalin saat dibuat (kebal ubah
-- tarif posisi); total = tarif x hari inklusif, dihitung backend.
-- Status: DRAFT/MENUNGGU_BAYAR/AKTIF/DIJEDA/DIBATALKAN (+tampilan
-- TERJADWAL/TAYANG/SELESAI dihitung dari periode).
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_AD_CAMPAIGN;

IF OBJECT_ID('dbo.T_AD_CAMPAIGN', 'U') IS NULL
CREATE TABLE dbo.T_AD_CAMPAIGN (
    CAMPAIGNID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CAMPAIGNCODE VARCHAR(30) NOT NULL,
    TITLE VARCHAR(150) NOT NULL,
    ADVERTISER VARCHAR(100) NOT NULL,
    CONTACT VARCHAR(100) NULL,
    BANNERIMAGE VARCHAR(255) NULL,
    LINKTYPE VARCHAR(10) NOT NULL DEFAULT 'EVENT',
    EVENTID INT NULL,
    LINKURL VARCHAR(500) NULL,
    POSITIONID INT NOT NULL,
    STARTDATE DATE NOT NULL,
    ENDDATE DATE NOT NULL,
    RATEPERDAY NUMERIC(18,2) NOT NULL DEFAULT 0,
    DAYCOUNT INT NOT NULL DEFAULT 0,
    TOTALCOST NUMERIC(18,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(15) NOT NULL DEFAULT 'DRAFT',
    PAIDAT DATETIME2 NULL,
    CANCELREASON VARCHAR(200) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_AD_CAMPAIGN_CODE' AND object_id = OBJECT_ID('dbo.T_AD_CAMPAIGN'))
CREATE UNIQUE INDEX UX_T_AD_CAMPAIGN_CODE ON dbo.T_AD_CAMPAIGN (CAMPAIGNCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AD_CAMPAIGN_STATUS' AND object_id = OBJECT_ID('dbo.T_AD_CAMPAIGN'))
CREATE INDEX IX_T_AD_CAMPAIGN_STATUS ON dbo.T_AD_CAMPAIGN (STATUS, POSITIONID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AD_CAMPAIGN_PERIOD' AND object_id = OBJECT_ID('dbo.T_AD_CAMPAIGN'))
CREATE INDEX IX_T_AD_CAMPAIGN_PERIOD ON dbo.T_AD_CAMPAIGN (POSITIONID, STARTDATE, ENDDATE);
GO

-- Perlebar STATUS bila tabel sudah terlanjur dibuat dengan VARCHAR(12)
-- ('MENUNGGU_BAYAR' = 14 karakter). Idempoten.
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.T_AD_CAMPAIGN') AND name = 'STATUS' AND max_length < 30)
ALTER TABLE dbo.T_AD_CAMPAIGN ALTER COLUMN STATUS VARCHAR(15) NOT NULL;
GO

