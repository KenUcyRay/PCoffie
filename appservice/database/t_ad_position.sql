-- Posisi iklan (Marketing Tools, module Marketing). Aturan: T_ prefix.
-- Satu baris = satu slot tayang (kapasitas = kampanye bersamaan maks).
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_AD_POSITION;

IF OBJECT_ID('dbo.T_AD_POSITION', 'U') IS NULL
CREATE TABLE dbo.T_AD_POSITION (
    POSITIONID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    POSCODE VARCHAR(20) NOT NULL,
    POSNAME VARCHAR(100) NOT NULL,
    DESCR VARCHAR(200) NULL,
    WIDTH INT NOT NULL DEFAULT 0,
    HEIGHT INT NOT NULL DEFAULT 0,
    RATEPERDAY NUMERIC(18,2) NOT NULL DEFAULT 0,
    CAPACITY INT NOT NULL DEFAULT 1,
    SORTORDER INT NOT NULL DEFAULT 0,
    ISACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_AD_POSITION_CODE' AND object_id = OBJECT_ID('dbo.T_AD_POSITION'))
CREATE UNIQUE INDEX UX_T_AD_POSITION_CODE ON dbo.T_AD_POSITION (POSCODE);
GO

