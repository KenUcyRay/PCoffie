-- Pengaturan umum aplikasi (App Setting, module System).
-- Aturan: tabel baru pakai awalan T_. Satu baris = pengaturan yang berlaku.
-- Perubahan dicatat di Audit Log (before/after), jadi tanpa tabel riwayat.
-- Password SMTP disimpan terenkripsi (dbo.app_encrypt).
-- Idempoten: CREATE hanya bila tabel belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_APP_SETTING;

IF OBJECT_ID('dbo.T_APP_SETTING', 'U') IS NULL
CREATE TABLE dbo.T_APP_SETTING (
    SETTINGID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    APPNAME VARCHAR(100) NOT NULL DEFAULT 'Tiket APP',
    SLOGAN VARCHAR(200) NULL,
    LOGO VARCHAR(255) NULL,
    FAVICON VARCHAR(255) NULL,
    CONTACTEMAIL VARCHAR(100) NULL,
    CONTACTPHONE VARCHAR(30) NULL,
    CONTACTWA VARCHAR(30) NULL,
    ADDRESS VARCHAR(500) NULL,
    TIMEZONE VARCHAR(30) NOT NULL DEFAULT 'Asia/Jakarta',
    CURRENCY VARCHAR(10) NOT NULL DEFAULT 'RP',
    DATEFORMAT VARCHAR(30) NULL,
    TERMS VARCHAR(MAX) NULL,
    PRIVACY VARCHAR(MAX) NULL,
    TERMSVERSION VARCHAR(50) NULL,
    MAILFROMNAME VARCHAR(100) NULL,
    MAILFROMEMAIL VARCHAR(100) NULL,
    SMTPHOST VARCHAR(100) NULL,
    SMTPPORT INT NULL,
    SMTPENCRYPTION VARCHAR(10) NULL,
    SMTPUSERNAME VARCHAR(100) NULL,
    SMTPPASSWORD NVARCHAR(MAX) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

-- Data awal: satu baris pengaturan (nilai contoh, bisa diubah dari halaman
-- General Setting).
INSERT INTO dbo.T_APP_SETTING
    (APPNAME, SLOGAN, TIMEZONE, CURRENCY, SYSCREATEUSER, SYSCREATEDATE)
SELECT 'Tiket APP', '', 'Asia/Jakarta', 'RP', 'SEED', GETDATE()
WHERE NOT EXISTS (SELECT 1 FROM dbo.T_APP_SETTING);

