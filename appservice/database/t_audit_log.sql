-- Tabel audit log (Log Center, module System). Aturan: tabel baru pakai awalan T_.
-- Append-only: UPDATE dan DELETE ditolak trigger di bawah (bukan cuma di aplikasi).
-- Idempoten: CREATE/trigger hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO) karena CREATE TRIGGER harus batch tersendiri.
-- ROLLBACK (hanya development): DROP TRIGGER ...; DROP TABLE ... (lihat bawah).

IF OBJECT_ID('dbo.T_AUDIT_LOG', 'U') IS NULL
CREATE TABLE dbo.T_AUDIT_LOG (
    LOGID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    LOGTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    USERID INT NULL,
    USERLOGIN VARCHAR(25) NULL,
    USERNAME VARCHAR(100) NULL,
    ACTION VARCHAR(10) NOT NULL,
    MCONTROL VARCHAR(25) NULL,
    PAGENAME VARCHAR(100) NULL,
    TABLENAME VARCHAR(50) NULL,
    DATAID VARCHAR(50) NULL,
    SUMMARY NVARCHAR(200) NULL,
    BEFOREJSON NVARCHAR(MAX) NULL,
    AFTERJSON NVARCHAR(MAX) NULL,
    USERIP VARCHAR(45) NULL,
    USERAGENT VARCHAR(255) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AUDIT_LOG_TIME' AND object_id = OBJECT_ID('dbo.T_AUDIT_LOG'))
CREATE INDEX IX_T_AUDIT_LOG_TIME ON dbo.T_AUDIT_LOG (LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AUDIT_LOG_USER' AND object_id = OBJECT_ID('dbo.T_AUDIT_LOG'))
CREATE INDEX IX_T_AUDIT_LOG_USER ON dbo.T_AUDIT_LOG (USERLOGIN, LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AUDIT_LOG_MENU' AND object_id = OBJECT_ID('dbo.T_AUDIT_LOG'))
CREATE INDEX IX_T_AUDIT_LOG_MENU ON dbo.T_AUDIT_LOG (MCONTROL, LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_AUDIT_LOG_ACTION' AND object_id = OBJECT_ID('dbo.T_AUDIT_LOG'))
CREATE INDEX IX_T_AUDIT_LOG_ACTION ON dbo.T_AUDIT_LOG (ACTION, LOGTIME DESC);
GO

-- Tolak UPDATE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_AUDIT_LOG_NOUPDATE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_AUDIT_LOG_NOUPDATE ON dbo.T_AUDIT_LOG INSTEAD OF UPDATE AS BEGIN RAISERROR(''T_AUDIT_LOG tidak boleh diubah.'', 16, 1); END');
GO

-- Tolak DELETE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_AUDIT_LOG_NODELETE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_AUDIT_LOG_NODELETE ON dbo.T_AUDIT_LOG INSTEAD OF DELETE AS BEGIN RAISERROR(''T_AUDIT_LOG tidak boleh dihapus.'', 16, 1); END');
GO

