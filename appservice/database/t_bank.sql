-- Tabel bank (Master Data, module System). Aturan: tabel baru pakai awalan T_.
-- Idempoten: CREATE hanya bila tabel belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_BANK;

IF OBJECT_ID('dbo.T_BANK', 'U') IS NULL
CREATE TABLE dbo.T_BANK (
    BANKID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    BANKCODE VARCHAR(20) NOT NULL,
    BANKNAME VARCHAR(100) NOT NULL,
    BANKSHORT VARCHAR(20) NOT NULL,
    BANKACTIVE VARCHAR(10) NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

