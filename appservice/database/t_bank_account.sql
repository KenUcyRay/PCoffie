-- Rekening bank tujuan payout/penarikan (Finance, module Finance). Aturan: T_ prefix.
-- Satu baris = satu rekening milik SELLER (FK T_SELLER) atau ORGANIZER (nama
-- dicocokkan ke T_EVENT.ORGNAME tanpa memandang kapital/spasi tepi).
-- Nomor tersimpan terenkripsi (ACCTENC via dbo.app_encrypt) + hash berkunci
-- HMAC-SHA256 (ACCTHASH) untuk cegah ganda tanpa menyimpan nomor mentah.
-- ACCTHASH diisi skrip PHP setelah migration (butuh FINANCE_HASH_SECRET),
-- lalu indeks unik di t_bank_account_keys.sql. Hanya LAST4 untuk tampilan.
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_BANK_ACCOUNT;

IF OBJECT_ID('dbo.T_BANK_ACCOUNT', 'U') IS NULL
CREATE TABLE dbo.T_BANK_ACCOUNT (
    BANKACCOUNTID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    OWNERTYPE VARCHAR(10) NOT NULL,
    SELLERID INT NULL,
    ORGNAME VARCHAR(100) NULL,
    ORGNORM AS (UPPER(LTRIM(RTRIM(ISNULL(ORGNAME, ''))))) PERSISTED,
    BANKID INT NOT NULL,
    ACCTENC VARCHAR(256) NOT NULL,
    ACCTHASH VARCHAR(64) NOT NULL DEFAULT '',
    LAST4 VARCHAR(4) NOT NULL,
    ACCTNAME VARCHAR(100) NOT NULL,
    ISPRIMARY VARCHAR(3) NOT NULL DEFAULT 'NO',
    VERIFYSTATUS VARCHAR(16) NOT NULL DEFAULT 'BELUM_VERIFIKASI',
    VERIFYNOTE VARCHAR(200) NULL,
    VERIFYBY VARCHAR(25) NULL,
    VERIFYAT DATETIME2 NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'AKTIF',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BANK_ACCOUNT_OWNER' AND object_id = OBJECT_ID('dbo.T_BANK_ACCOUNT'))
CREATE INDEX IX_T_BANK_ACCOUNT_OWNER ON dbo.T_BANK_ACCOUNT (OWNERTYPE, SELLERID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BANK_ACCOUNT_BANK' AND object_id = OBJECT_ID('dbo.T_BANK_ACCOUNT'))
CREATE INDEX IX_T_BANK_ACCOUNT_BANK ON dbo.T_BANK_ACCOUNT (BANKID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BANK_ACCOUNT_VERIFY' AND object_id = OBJECT_ID('dbo.T_BANK_ACCOUNT'))
CREATE INDEX IX_T_BANK_ACCOUNT_VERIFY ON dbo.T_BANK_ACCOUNT (VERIFYSTATUS, STATUS);
GO

