-- Blokir akses login (Security Center, module System). Aturan: tabel baru pakai awalan T_.
-- Data TIDAK dihapus: membuka blokir mengubah STATUS (AKTIF -> DIBUKA),
-- blokir lewat waktu menjadi KEDALUWARSA otomatis. Tidak perlu data awal.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_BLOCKED_ACCESS;

IF OBJECT_ID('dbo.T_BLOCKED_ACCESS', 'U') IS NULL
CREATE TABLE dbo.T_BLOCKED_ACCESS (
    BLOCKID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    BLOCKTYPE VARCHAR(10) NOT NULL,
    BLOCKVALUE VARCHAR(45) NOT NULL,
    SOURCE VARCHAR(10) NOT NULL DEFAULT 'MANUAL',
    REASON VARCHAR(200) NULL,
    STARTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    ENDTIME DATETIME2 NULL,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'AKTIF',
    UNBLOCKTIME DATETIME2 NULL,
    UNBLOCKBY VARCHAR(25) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BLOCKED_ACCESS_TYPE' AND object_id = OBJECT_ID('dbo.T_BLOCKED_ACCESS'))
CREATE INDEX IX_T_BLOCKED_ACCESS_TYPE ON dbo.T_BLOCKED_ACCESS (BLOCKTYPE, STARTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BLOCKED_ACCESS_VALUE' AND object_id = OBJECT_ID('dbo.T_BLOCKED_ACCESS'))
CREATE INDEX IX_T_BLOCKED_ACCESS_VALUE ON dbo.T_BLOCKED_ACCESS (BLOCKVALUE, STARTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_BLOCKED_ACCESS_STATUS' AND object_id = OBJECT_ID('dbo.T_BLOCKED_ACCESS'))
CREATE INDEX IX_T_BLOCKED_ACCESS_STATUS ON dbo.T_BLOCKED_ACCESS (STATUS, STARTIME DESC);
GO

-- Perbaikan: STATUS butuh 12 char untuk nilai KEDALUWARSA (idempoten).
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.T_BLOCKED_ACCESS') AND name = 'STATUS' AND max_length < 12)
ALTER TABLE dbo.T_BLOCKED_ACCESS ALTER COLUMN STATUS VARCHAR(12) NOT NULL;
GO

