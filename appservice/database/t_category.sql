-- Tabel kategori event (Master Data, module System).
-- Aturan baru: tabel baru pakai awalan T_ (bukan CP_).
-- Idempoten: CREATE hanya bila tabel belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_CATEGORY;

IF OBJECT_ID('dbo.T_CATEGORY', 'U') IS NULL
CREATE TABLE dbo.T_CATEGORY (
    CATID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CATCODE VARCHAR(20) NOT NULL,
    CATNAME VARCHAR(100) NOT NULL,
    CATSORT NUMERIC(18,0) NULL DEFAULT 0,
    CATACTIVE VARCHAR(10) NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

