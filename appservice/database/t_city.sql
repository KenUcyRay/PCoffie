-- Tabel kota (Master Data, module System). Aturan: tabel baru pakai awalan T_.
-- Idempoten: CREATE hanya bila tabel belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_CITY;

IF OBJECT_ID('dbo.T_CITY', 'U') IS NULL
CREATE TABLE dbo.T_CITY (
    CITYID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CITYCODE VARCHAR(20) NOT NULL,
    CITYNAME VARCHAR(100) NOT NULL,
    CITYPROV VARCHAR(100) NOT NULL,
    CITYTZ VARCHAR(10) NOT NULL,
    CITYACTIVE VARCHAR(10) NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

