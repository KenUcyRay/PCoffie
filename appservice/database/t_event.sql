-- Event (Event Management, module Event). Aturan: tabel baru pakai awalan T_.
-- Satu baris = satu event. Relasi kategori/kota lewat KODE (CATCODE/CITYCODE),
-- tanpa FK fisik (mengikuti pola project). Status: DRAFT/PUBLISHED/ENDED/CANCELLED.
-- ENDED dihitung lazy saat data diakses (tanpa scheduler).
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_EVENT;

IF OBJECT_ID('dbo.T_EVENT', 'U') IS NULL
CREATE TABLE dbo.T_EVENT (
    EVENTID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    EVENTCODE VARCHAR(30) NOT NULL,
    SLUG VARCHAR(150) NOT NULL,
    TITLE VARCHAR(150) NOT NULL,
    DESCR VARCHAR(MAX) NULL,
    CATCODE VARCHAR(20) NULL,
    CITYCODE VARCHAR(20) NULL,
    VENUE VARCHAR(150) NULL,
    ADDRESS VARCHAR(500) NULL,
    LATITUDE NUMERIC(10,7) NULL,
    LONGITUDE NUMERIC(10,7) NULL,
    STARTAT DATETIME2 NULL,
    ENDAT DATETIME2 NULL,
    POSTER VARCHAR(255) NULL,
    ORGNAME VARCHAR(100) NULL,
    ORGCONTACT VARCHAR(100) NULL,
    TERMS VARCHAR(MAX) NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'DRAFT',
    CANCELREASON VARCHAR(200) NULL,
    PUBLISHEDAT DATETIME2 NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_EVENT_CODE' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE UNIQUE INDEX UX_T_EVENT_CODE ON dbo.T_EVENT (EVENTCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_EVENT_SLUG' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE UNIQUE INDEX UX_T_EVENT_SLUG ON dbo.T_EVENT (SLUG);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_EVENT_STATUS' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE INDEX IX_T_EVENT_STATUS ON dbo.T_EVENT (STATUS, STARTAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_EVENT_CAT' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE INDEX IX_T_EVENT_CAT ON dbo.T_EVENT (CATCODE, STARTAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_EVENT_CITY' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE INDEX IX_T_EVENT_CITY ON dbo.T_EVENT (CITYCODE, STARTAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_EVENT_START' AND object_id = OBJECT_ID('dbo.T_EVENT'))
CREATE INDEX IX_T_EVENT_START ON dbo.T_EVENT (STARTAT DESC);
GO

