-- Tabel riwayat versi pengaturan fee (Master Data, module System).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu versi lengkap.
-- Versi lama tidak diubah/dihapus; yang berlaku = AKTIF dengan tanggal
-- mulai paling baru yang sudah tiba. Idempoten + rollback di bawah.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_FEE_SETTING;

IF OBJECT_ID('dbo.T_FEE_SETTING', 'U') IS NULL
CREATE TABLE dbo.T_FEE_SETTING (
    FEEID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    EFFECTIVEFROM DATE NOT NULL,
    PLATFORMPCT NUMERIC(5,2) NULL DEFAULT 0,
    PLATFORMFIX NUMERIC(18,2) NULL DEFAULT 0,
    SERVICEPERTICKET NUMERIC(18,2) NULL DEFAULT 0,
    WITHDRAWFEE NUMERIC(18,2) NULL DEFAULT 0,
    MINWITHDRAW NUMERIC(18,2) NULL DEFAULT 0,
    PAYOUTWAITDAYS INT NULL DEFAULT 0,
    PAYTIMEOUTMIN INT NULL DEFAULT 15,
    FEESTATUS VARCHAR(10) NULL DEFAULT 'AKTIF',
    FEENOTE VARCHAR(200) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

-- Seed: versi awal berlaku sejak hari pertama aplikasi dipakai (idempoten).
INSERT INTO dbo.T_FEE_SETTING
    (EFFECTIVEFROM, PLATFORMPCT, PLATFORMFIX, SERVICEPERTICKET, WITHDRAWFEE,
     MINWITHDRAW, PAYOUTWAITDAYS, PAYTIMEOUTMIN, FEESTATUS, FEENOTE, SYSCREATEUSER, SYSCREATEDATE)
SELECT '2024-01-01', 5, 0, 5000, 6500, 50000, 3, 15, 'AKTIF', 'Versi awal', 'SEED', GETDATE()
WHERE NOT EXISTS (SELECT 1 FROM dbo.T_FEE_SETTING WHERE EFFECTIVEFROM = '2024-01-01' AND FEESTATUS = 'AKTIF');

