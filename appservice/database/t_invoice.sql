-- Invoice (Finance, module Finance). Aturan: T_ prefix.
-- Terbit otomatis oleh layanan pembayaran; TANPA endpoint tambah/ubah/hapus.
-- Isi tidak boleh diubah setelah terbit (hanya STATUS -> DIBATALKAN).
-- Nomor unik format INV/YYYYMM/6-digit, urut per bulan.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan (GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_INVOICE;

IF OBJECT_ID('dbo.T_INVOICE', 'U') IS NULL
CREATE TABLE dbo.T_INVOICE (
    INVOICEID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    INVNO VARCHAR(20) NOT NULL,
    PAYMENTID INT NOT NULL,
    REFTYPE VARCHAR(10) NOT NULL,
    ISSUEDATE DATE NOT NULL,
    RECIPIENT VARCHAR(100) NOT NULL,
    RECIPIENTEMAIL VARCHAR(100) NULL,
    RECIPIENTADDR VARCHAR(500) NULL,
    LINES NVARCHAR(MAX) NULL,
    TOTAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'TERBIT',
    CANCELREASON VARCHAR(200) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_INVOICE_NO' AND object_id = OBJECT_ID('dbo.T_INVOICE'))
CREATE UNIQUE INDEX UX_T_INVOICE_NO ON dbo.T_INVOICE (INVNO);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_INVOICE_PAYMENT' AND object_id = OBJECT_ID('dbo.T_INVOICE'))
CREATE UNIQUE INDEX UX_T_INVOICE_PAYMENT ON dbo.T_INVOICE (PAYMENTID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_INVOICE_ISSUED' AND object_id = OBJECT_ID('dbo.T_INVOICE'))
CREATE INDEX IX_T_INVOICE_ISSUED ON dbo.T_INVOICE (ISSUEDATE DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_INVOICE_STATUS' AND object_id = OBJECT_ID('dbo.T_INVOICE'))
CREATE INDEX IX_T_INVOICE_STATUS ON dbo.T_INVOICE (STATUS);
GO

