-- Tabel riwayat login (Log Center, module System). Aturan: tabel baru pakai awalan T_.
-- Password yang diketik TIDAK PERNAH disimpan (tidak ada kolomnya).
-- Append-only: UPDATE dan DELETE ditolak trigger di bawah (bukan cuma di aplikasi).
-- Idempoten: CREATE/trigger/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO) karena CREATE TRIGGER harus batch tersendiri.
-- ROLLBACK (hanya development): DROP TRIGGER ...; DROP TABLE ... (lihat bawah).

IF OBJECT_ID('dbo.T_LOGIN_HISTORY', 'U') IS NULL
CREATE TABLE dbo.T_LOGIN_HISTORY (
    LOGINID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    LOGTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    TYPEDUSER VARCHAR(25) NULL,
    USERID INT NULL,
    RESULT VARCHAR(10) NOT NULL,
    FAILREASON VARCHAR(20) NULL,
    USERIP VARCHAR(45) NULL,
    USERAGENT VARCHAR(255) NULL,
    DEVICE VARCHAR(100) NULL,
    BROWSER VARCHAR(100) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_LOGIN_HISTORY_TIME' AND object_id = OBJECT_ID('dbo.T_LOGIN_HISTORY'))
CREATE INDEX IX_T_LOGIN_HISTORY_TIME ON dbo.T_LOGIN_HISTORY (LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_LOGIN_HISTORY_USER' AND object_id = OBJECT_ID('dbo.T_LOGIN_HISTORY'))
CREATE INDEX IX_T_LOGIN_HISTORY_USER ON dbo.T_LOGIN_HISTORY (TYPEDUSER, LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_LOGIN_HISTORY_RESULT' AND object_id = OBJECT_ID('dbo.T_LOGIN_HISTORY'))
CREATE INDEX IX_T_LOGIN_HISTORY_RESULT ON dbo.T_LOGIN_HISTORY (RESULT, LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_LOGIN_HISTORY_IP' AND object_id = OBJECT_ID('dbo.T_LOGIN_HISTORY'))
CREATE INDEX IX_T_LOGIN_HISTORY_IP ON dbo.T_LOGIN_HISTORY (USERIP, LOGTIME DESC);
GO

-- Tolak UPDATE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_LOGIN_HISTORY_NOUPDATE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_LOGIN_HISTORY_NOUPDATE ON dbo.T_LOGIN_HISTORY INSTEAD OF UPDATE AS BEGIN RAISERROR(''T_LOGIN_HISTORY tidak boleh diubah.'', 16, 1); END');
GO

-- Tolak DELETE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_LOGIN_HISTORY_NODELETE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_LOGIN_HISTORY_NODELETE ON dbo.T_LOGIN_HISTORY INSTEAD OF DELETE AS BEGIN RAISERROR(''T_LOGIN_HISTORY tidak boleh dihapus.'', 16, 1); END');
GO

