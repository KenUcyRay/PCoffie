-- Keluhan pesanan merchandise (My Purchase / Seller Order).
-- Aturan: tabel baru pakai awalan T_. Satu keluhan TERBUKA per pesanan.
-- Alasan tetap: BARANG_RUSAK, TIDAK_SESUAI, TIDAK_DITERIMA, LAINNYA.
-- Status: TERBUKA/DITANGGAPI/SELESAI. Menutup wajib mengisi tanggapan.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_MERCH_COMPLAINT;

IF OBJECT_ID('dbo.T_MERCH_COMPLAINT', 'U') IS NULL
CREATE TABLE dbo.T_MERCH_COMPLAINT (
    COMPLAINTID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ORDERID INT NOT NULL,
    REASON VARCHAR(20) NOT NULL,
    DESCR VARCHAR(1000) NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'TERBUKA',
    RESPONSE VARCHAR(1000) NULL,
    CREATETIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    CREATEBY VARCHAR(25) NULL,
    RESPONDTIME DATETIME2 NULL,
    RESPONDBY VARCHAR(25) NULL,
    DONETIME DATETIME2 NULL,
    DONEBY VARCHAR(25) NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MERCH_COMPLAINT_ORDER' AND object_id = OBJECT_ID('dbo.T_MERCH_COMPLAINT'))
CREATE INDEX IX_T_MERCH_COMPLAINT_ORDER ON dbo.T_MERCH_COMPLAINT (ORDERID, CREATETIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MERCH_COMPLAINT_STATUS' AND object_id = OBJECT_ID('dbo.T_MERCH_COMPLAINT'))
CREATE INDEX IX_T_MERCH_COMPLAINT_STATUS ON dbo.T_MERCH_COMPLAINT (STATUS, CREATETIME DESC);
GO

