-- Pesanan merchandise (My Purchase / Seller Order, module Merchandise).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu pesanan.
-- Status: BARU/DIPROSES/DIKIRIM/SELESAI/DIBATALKAN/DIKEMBALIKAN.
-- Bayar: BELUM_BAYAR/LUNAS/REFUND. Harga disalin ke item (kebal ubah harga).
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_MERCH_ORDER;

IF OBJECT_ID('dbo.T_MERCH_ORDER', 'U') IS NULL
CREATE TABLE dbo.T_MERCH_ORDER (
    ORDERID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ORDERNO VARCHAR(30) NOT NULL,
    SELLERID INT NOT NULL,
    BUYERNAME VARCHAR(100) NOT NULL,
    BUYERPHONE VARCHAR(30) NULL,
    BUYEREMAIL VARCHAR(100) NULL,
    ADDRESS VARCHAR(500) NOT NULL,
    CITY VARCHAR(100) NULL,
    PROVINCE VARCHAR(100) NULL,
    POSTALCODE VARCHAR(10) NULL,
    COURIER VARCHAR(20) NULL,
    TRACKINGNO VARCHAR(50) NULL,
    SUBTOTAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    SHIPPING NUMERIC(18,2) NOT NULL DEFAULT 0,
    TOTAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    ORDERSTATUS VARCHAR(12) NOT NULL DEFAULT 'BARU',
    PAYSTATUS VARCHAR(12) NOT NULL DEFAULT 'BELUM_BAYAR',
    PAIDAT DATETIME2 NULL,
    PAYDEADLINE DATETIME2 NULL,
    SHIPPEDAT DATETIME2 NULL,
    DONEAT DATETIME2 NULL,
    NOTE VARCHAR(500) NULL,
    IDEMPOTENCYKEY VARCHAR(64) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_MERCH_ORDER_NO' AND object_id = OBJECT_ID('dbo.T_MERCH_ORDER'))
CREATE UNIQUE INDEX UX_T_MERCH_ORDER_NO ON dbo.T_MERCH_ORDER (ORDERNO);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_MERCH_ORDER_IDEMPOTENCY' AND object_id = OBJECT_ID('dbo.T_MERCH_ORDER'))
CREATE UNIQUE INDEX UX_T_MERCH_ORDER_IDEMPOTENCY ON dbo.T_MERCH_ORDER (IDEMPOTENCYKEY) WHERE IDEMPOTENCYKEY IS NOT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MERCH_ORDER_SELLER' AND object_id = OBJECT_ID('dbo.T_MERCH_ORDER'))
CREATE INDEX IX_T_MERCH_ORDER_SELLER ON dbo.T_MERCH_ORDER (SELLERID, ORDERSTATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MERCH_ORDER_STATUS' AND object_id = OBJECT_ID('dbo.T_MERCH_ORDER'))
CREATE INDEX IX_T_MERCH_ORDER_STATUS ON dbo.T_MERCH_ORDER (ORDERSTATUS, PAYSTATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MERCH_ORDER_TIME' AND object_id = OBJECT_ID('dbo.T_MERCH_ORDER'))
CREATE INDEX IX_T_MERCH_ORDER_TIME ON dbo.T_MERCH_ORDER (SYSCREATEDATE DESC);
GO

