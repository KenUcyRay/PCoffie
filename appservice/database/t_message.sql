-- Pesan broadcast dalam aplikasi (Broadcast Message, module System).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu pesan terkirim.
-- Isi pesan TIDAK bisa diubah; pesan salah ditarik (STATUS DITARIK).
-- Tanpa hapus fisik. Daftar target dibekukan sebagai JSON saat kirim.
-- Tidak perlu data awal.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_MESSAGE;

IF OBJECT_ID('dbo.T_MESSAGE', 'U') IS NULL
CREATE TABLE dbo.T_MESSAGE (
    MSGID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TITLE VARCHAR(100) NOT NULL,
    BODY VARCHAR(2000) NOT NULL,
    PRIORITY VARCHAR(10) NOT NULL DEFAULT 'INFO',
    TARGETTYPE VARCHAR(10) NOT NULL,
    TARGETJSON VARCHAR(MAX) NULL,
    CHANNEL VARCHAR(10) NOT NULL DEFAULT 'IN_APP',
    SENTAT DATETIME2 NOT NULL DEFAULT GETDATE(),
    EXPIRESAT DATETIME2 NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'TERKIRIM',
    RECIPIENTCOUNT INT NOT NULL DEFAULT 0,
    SENDERID INT NULL,
    SENDERLOGIN VARCHAR(25) NULL,
    RECALLTIME DATETIME2 NULL,
    RECALLBY VARCHAR(25) NULL,
    RECALLREASON VARCHAR(200) NULL,
    IDEMPOTENCYKEY VARCHAR(64) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_SENT' AND object_id = OBJECT_ID('dbo.T_MESSAGE'))
CREATE INDEX IX_T_MESSAGE_SENT ON dbo.T_MESSAGE (SENTAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_STATUS' AND object_id = OBJECT_ID('dbo.T_MESSAGE'))
CREATE INDEX IX_T_MESSAGE_STATUS ON dbo.T_MESSAGE (STATUS, SENTAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_IDEMPOTENCY' AND object_id = OBJECT_ID('dbo.T_MESSAGE'))
CREATE UNIQUE INDEX IX_T_MESSAGE_IDEMPOTENCY ON dbo.T_MESSAGE (IDEMPOTENCYKEY) WHERE IDEMPOTENCYKEY IS NOT NULL;
GO

