-- Penerima pesan broadcast (Broadcast Message, module System).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu penerima (dibuat
-- saat pesan dikirim; user baru di group tidak ikut pesan lama).
-- Status baca hanya BELUM_DIBACA/DIBACA. Tidak perlu data awal.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_MESSAGE_RECIPIENT;

IF OBJECT_ID('dbo.T_MESSAGE_RECIPIENT', 'U') IS NULL
CREATE TABLE dbo.T_MESSAGE_RECIPIENT (
    RECIPIENTID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MSGID BIGINT NOT NULL,
    USERID INT NULL,
    USERLOGIN VARCHAR(25) NULL,
    READSTATUS VARCHAR(12) NOT NULL DEFAULT 'BELUM_DIBACA',
    READTIME DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_RECIPIENT_MSG' AND object_id = OBJECT_ID('dbo.T_MESSAGE_RECIPIENT'))
CREATE INDEX IX_T_MESSAGE_RECIPIENT_MSG ON dbo.T_MESSAGE_RECIPIENT (MSGID, READSTATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_RECIPIENT_USER' AND object_id = OBJECT_ID('dbo.T_MESSAGE_RECIPIENT'))
CREATE INDEX IX_T_MESSAGE_RECIPIENT_USER ON dbo.T_MESSAGE_RECIPIENT (USERLOGIN, READSTATUS, MSGID DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_MESSAGE_RECIPIENT_READ' AND object_id = OBJECT_ID('dbo.T_MESSAGE_RECIPIENT'))
CREATE INDEX IX_T_MESSAGE_RECIPIENT_READ ON dbo.T_MESSAGE_RECIPIENT (READSTATUS, MSGID DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_MESSAGE_RECIPIENT_MSGUSER' AND object_id = OBJECT_ID('dbo.T_MESSAGE_RECIPIENT'))
CREATE UNIQUE INDEX UX_T_MESSAGE_RECIPIENT_MSGUSER ON dbo.T_MESSAGE_RECIPIENT (MSGID, USERID);
GO

