-- Berita (Content Management, module Marketing).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu berita.
-- Status: DRAFT/TERJADWAL/TERBIT/DIARSIPKAN. TERJADWAL otomatis TERBIT
-- saat diakses (lazy, tanpa scheduler). Slug beku setelah pernah terbit.
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_NEWS;

IF OBJECT_ID('dbo.T_NEWS', 'U') IS NULL
CREATE TABLE dbo.T_NEWS (
    NEWSID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TITLE VARCHAR(150) NOT NULL,
    SLUG VARCHAR(150) NOT NULL,
    SUMMARY VARCHAR(300) NULL,
    BODY VARCHAR(MAX) NULL,
    MAINIMAGE VARCHAR(255) NULL,
    NEWSCATCODE VARCHAR(20) NULL,
    EVENTCATCODE VARCHAR(20) NULL,
    EVENTID INT NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'DRAFT',
    PUBLISHEDAT DATETIME2 NULL,
    SCHEDULEDAT DATETIME2 NULL,
    AUTHORID INT NULL,
    AUTHORLOGIN VARCHAR(25) NULL,
    VIEWCOUNT INT NOT NULL DEFAULT 0,
    EVERPUBLISHED VARCHAR(3) NOT NULL DEFAULT 'NO',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_NEWS_SLUG' AND object_id = OBJECT_ID('dbo.T_NEWS'))
CREATE UNIQUE INDEX UX_T_NEWS_SLUG ON dbo.T_NEWS (SLUG);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_NEWS_STATUS' AND object_id = OBJECT_ID('dbo.T_NEWS'))
CREATE INDEX IX_T_NEWS_STATUS ON dbo.T_NEWS (STATUS, PUBLISHEDAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_NEWS_CAT' AND object_id = OBJECT_ID('dbo.T_NEWS'))
CREATE INDEX IX_T_NEWS_CAT ON dbo.T_NEWS (NEWSCATCODE, STATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_NEWS_PUBTIME' AND object_id = OBJECT_ID('dbo.T_NEWS'))
CREATE INDEX IX_T_NEWS_PUBTIME ON dbo.T_NEWS (PUBLISHEDAT DESC);
GO

