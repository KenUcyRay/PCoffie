-- Kategori berita (Content Management, module Marketing).
-- BUKAN kategori event (itu T_CATEGORY). Satu baris = satu kategori berita.
-- Idempoten: CREATE/index hanya bila belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_NEWS_CATEGORY;

IF OBJECT_ID('dbo.T_NEWS_CATEGORY', 'U') IS NULL
CREATE TABLE dbo.T_NEWS_CATEGORY (
    NEWSCATID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    CATCODE VARCHAR(20) NOT NULL,
    CATNAME VARCHAR(100) NOT NULL,
    SLUG VARCHAR(150) NOT NULL,
    CATSORT INT NOT NULL DEFAULT 0,
    CATACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_NEWS_CATEGORY_CODE' AND object_id = OBJECT_ID('dbo.T_NEWS_CATEGORY'))
CREATE UNIQUE INDEX UX_T_NEWS_CATEGORY_CODE ON dbo.T_NEWS_CATEGORY (CATCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_NEWS_CATEGORY_NAME' AND object_id = OBJECT_ID('dbo.T_NEWS_CATEGORY'))
CREATE UNIQUE INDEX UX_T_NEWS_CATEGORY_NAME ON dbo.T_NEWS_CATEGORY (CATNAME);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_NEWS_CATEGORY_SLUG' AND object_id = OBJECT_ID('dbo.T_NEWS_CATEGORY'))
CREATE UNIQUE INDEX UX_T_NEWS_CATEGORY_SLUG ON dbo.T_NEWS_CATEGORY (SLUG);
GO

