-- Pembayaran pusat (Finance, module Finance). Aturan: T_ prefix.
-- Satu baris = satu pembayaran. Satu referensi hanya boleh punya satu
-- pembayaran BERHASIL (indeks unik bersyarat UX_T_PAYMENT_REF_SUCCESS).
-- Semua uang NUMERIC(18,2) berisi rupiah penuh (dihitung Money helper).
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_PAYMENT;

IF OBJECT_ID('dbo.T_PAYMENT', 'U') IS NULL
CREATE TABLE dbo.T_PAYMENT (
    PAYMENTID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PAYNO VARCHAR(30) NOT NULL,
    REFTYPE VARCHAR(10) NOT NULL,
    REFID INT NOT NULL,
    EVENTID INT NULL,
    SELLERID INT NULL,
    PAYMETHODID INT NULL,
    SUBTOTAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    DISCOUNT NUMERIC(18,2) NOT NULL DEFAULT 0,
    PROMOCODE VARCHAR(20) NULL,
    SERVICEFEE NUMERIC(18,2) NOT NULL DEFAULT 0,
    SHIPPING NUMERIC(18,2) NOT NULL DEFAULT 0,
    TOTALPAID NUMERIC(18,2) NOT NULL DEFAULT 0,
    PLATFORMFEE NUMERIC(18,2) NOT NULL DEFAULT 0,
    METHODFEE NUMERIC(18,2) NOT NULL DEFAULT 0,
    OWNERAMT NUMERIC(18,2) NOT NULL DEFAULT 0,
    EXTREF VARCHAR(100) NULL,
    PAIDAT DATETIME2 NOT NULL,
    SOURCE VARCHAR(10) NOT NULL DEFAULT 'MANUAL',
    STATUS VARCHAR(12) NOT NULL DEFAULT 'BERHASIL',
    NOTE VARCHAR(200) NULL,
    CANCELREASON VARCHAR(200) NULL,
    CANCELBY VARCHAR(25) NULL,
    CANCELAT DATETIME2 NULL,
    IDEMPOTENCYKEY VARCHAR(64) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PAYMENT_NO' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE UNIQUE INDEX UX_T_PAYMENT_NO ON dbo.T_PAYMENT (PAYNO);
GO

-- Satu referensi = satu pembayaran BERHASIL (level database, anti dobel
-- concurrent). Batalkan dulu yang lama sebelum catat pengganti.
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PAYMENT_REF_SUCCESS' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE UNIQUE INDEX UX_T_PAYMENT_REF_SUCCESS ON dbo.T_PAYMENT (REFTYPE, REFID) WHERE STATUS = 'BERHASIL';
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_PAIDAT' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE INDEX IX_T_PAYMENT_PAIDAT ON dbo.T_PAYMENT (PAIDAT DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_TYPE' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE INDEX IX_T_PAYMENT_TYPE ON dbo.T_PAYMENT (REFTYPE, STATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_EVENT' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE INDEX IX_T_PAYMENT_EVENT ON dbo.T_PAYMENT (EVENTID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_SELLER' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE INDEX IX_T_PAYMENT_SELLER ON dbo.T_PAYMENT (SELLERID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_EXTREF' AND object_id = OBJECT_ID('dbo.T_PAYMENT'))
CREATE INDEX IX_T_PAYMENT_EXTREF ON dbo.T_PAYMENT (EXTREF);
GO

