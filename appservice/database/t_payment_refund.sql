-- Refund pembayaran (Finance, module Finance). Aturan: T_ prefix.
-- Hanya-tambah seperti T_AUDIT_LOG: tidak bisa diubah/dihapus lewat aplikasi,
-- dilindungi trigger di level database dengan cara yang sama.
-- Nominal dikembalikan dihitung dari tabel ini (SUM), bukan kolom terpisah.
-- Idempoten: CREATE/index/trigger hanya bila belum ada. CREATE TRIGGER harus
-- batch tersendiri (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu):
-- DROP TRIGGER IF EXISTS dbo.TRG_T_PAYMENT_REFUND_NOUPDATE;
-- DROP TRIGGER IF EXISTS dbo.TRG_T_PAYMENT_REFUND_NODELETE;
-- DROP TABLE dbo.T_PAYMENT_REFUND;

IF OBJECT_ID('dbo.T_PAYMENT_REFUND', 'U') IS NULL
CREATE TABLE dbo.T_PAYMENT_REFUND (
    REFUNDID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PAYMENTID INT NOT NULL,
    AMOUNT NUMERIC(18,2) NOT NULL DEFAULT 0,
    REFUNDTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    REFUNDTYPE VARCHAR(12) NOT NULL,
    REFID INT NOT NULL,
    ACTOR VARCHAR(25) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYMENT_REFUND_PAY' AND object_id = OBJECT_ID('dbo.T_PAYMENT_REFUND'))
CREATE INDEX IX_T_PAYMENT_REFUND_PAY ON dbo.T_PAYMENT_REFUND (PAYMENTID);
GO

IF OBJECT_ID('dbo.TRG_T_PAYMENT_REFUND_NOUPDATE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_PAYMENT_REFUND_NOUPDATE ON dbo.T_PAYMENT_REFUND INSTEAD OF UPDATE AS BEGIN RAISERROR(''T_PAYMENT_REFUND tidak boleh diubah.'',16,1); END');
GO

IF OBJECT_ID('dbo.TRG_T_PAYMENT_REFUND_NODELETE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_PAYMENT_REFUND_NODELETE ON dbo.T_PAYMENT_REFUND INSTEAD OF DELETE AS BEGIN RAISERROR(''T_PAYMENT_REFUND tidak boleh dihapus.'',16,1); END');
GO

