-- Payout penyelenggara (Finance, module Finance). Aturan: T_ prefix.
-- Satu baris = satu pengajuan pencairan event. Hitungan disalin saat diajukan
-- (kebal ubah Fee Setting/refund sesudahnya). Satu event hanya boleh punya
-- satu payout DIAJUKAN/DIPROSES/BERHASIL (indeks unik bersyarat).
-- Alur: DIAJUKAN -> DIPROSES -> BERHASIL; DIAJUKAN/DIPROSES -> DITOLAK/GAGAL.
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_PAYOUT;

IF OBJECT_ID('dbo.T_PAYOUT', 'U') IS NULL
CREATE TABLE dbo.T_PAYOUT (
    PAYOUTID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PONO VARCHAR(30) NOT NULL,
    EVENTID INT NOT NULL,
    ORGNAME VARCHAR(100) NOT NULL,
    BANKACCOUNTID INT NOT NULL,
    TICKETCOUNT INT NOT NULL DEFAULT 0,
    GROSS NUMERIC(18,2) NOT NULL DEFAULT 0,
    DISCOUNT NUMERIC(18,2) NOT NULL DEFAULT 0,
    PLATFORMFEE NUMERIC(18,2) NOT NULL DEFAULT 0,
    REFUND NUMERIC(18,2) NOT NULL DEFAULT 0,
    NETAMOUNT NUMERIC(18,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'DIAJUKAN',
    TRANSFERREF VARCHAR(100) NULL,
    TRANSFERDATE DATE NULL,
    PROOFIMAGE VARCHAR(255) NULL,
    REASON VARCHAR(200) NULL,
    REQUESTBY VARCHAR(25) NULL,
    REQUESTAT DATETIME2 NULL,
    PROCESSBY VARCHAR(25) NULL,
    PROCESSAT DATETIME2 NULL,
    DONEBY VARCHAR(25) NULL,
    DONEAT DATETIME2 NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PAYOUT_NO' AND object_id = OBJECT_ID('dbo.T_PAYOUT'))
CREATE UNIQUE INDEX UX_T_PAYOUT_NO ON dbo.T_PAYOUT (PONO);
GO

-- Satu event = satu payout aktif atas (anti dobel concurrent).
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PAYOUT_EVENT_ACTIVE' AND object_id = OBJECT_ID('dbo.T_PAYOUT'))
CREATE UNIQUE INDEX UX_T_PAYOUT_EVENT_ACTIVE ON dbo.T_PAYOUT (EVENTID)
WHERE STATUS IN ('DIAJUKAN', 'DIPROSES', 'BERHASIL');
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYOUT_EVENT' AND object_id = OBJECT_ID('dbo.T_PAYOUT'))
CREATE INDEX IX_T_PAYOUT_EVENT ON dbo.T_PAYOUT (EVENTID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PAYOUT_STATUS' AND object_id = OBJECT_ID('dbo.T_PAYOUT'))
CREATE INDEX IX_T_PAYOUT_STATUS ON dbo.T_PAYOUT (STATUS);
GO

