-- Produk merchandise (Seller Center, module Merchandise).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu produk.
-- Harga NUMERIC presisi tetap (0 = gratis, ikut validasi berbayar).
-- Kategori whitelist di kode: Lightstick, Photocard, Figure, Apparel,
-- Poster, Aksesori, Lainnya. Kondisi: BARU/BEKAS.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_PRODUCT;

IF OBJECT_ID('dbo.T_PRODUCT', 'U') IS NULL
CREATE TABLE dbo.T_PRODUCT (
    PRODUCTID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PRODUCTCODE VARCHAR(30) NOT NULL,
    SELLERID INT NOT NULL,
    NAME VARCHAR(150) NOT NULL,
    DESCR VARCHAR(MAX) NULL,
    CATEGORY VARCHAR(20) NOT NULL,
    PRICE NUMERIC(18,2) NOT NULL DEFAULT 0,
    STOCK INT NOT NULL DEFAULT 0,
    CONDITION VARCHAR(10) NOT NULL DEFAULT 'BARU',
    WEIGHT INT NOT NULL DEFAULT 0,
    ISACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PRODUCT_CODE' AND object_id = OBJECT_ID('dbo.T_PRODUCT'))
CREATE UNIQUE INDEX UX_T_PRODUCT_CODE ON dbo.T_PRODUCT (PRODUCTCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PRODUCT_SELLER' AND object_id = OBJECT_ID('dbo.T_PRODUCT'))
CREATE INDEX IX_T_PRODUCT_SELLER ON dbo.T_PRODUCT (SELLERID, ISACTIVE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PRODUCT_CAT' AND object_id = OBJECT_ID('dbo.T_PRODUCT'))
CREATE INDEX IX_T_PRODUCT_CAT ON dbo.T_PRODUCT (CATEGORY, ISACTIVE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PRODUCT_STATUS' AND object_id = OBJECT_ID('dbo.T_PRODUCT'))
CREATE INDEX IX_T_PRODUCT_STATUS ON dbo.T_PRODUCT (ISACTIVE, STOCK);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PRODUCT_NAME' AND object_id = OBJECT_ID('dbo.T_PRODUCT'))
CREATE INDEX IX_T_PRODUCT_NAME ON dbo.T_PRODUCT (NAME);
GO

