-- Promo tiket event (Marketing Tools, module Marketing).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu kode promo.
-- Kode huruf besar unik. Uang NUMERIC presisi tetap (bukan float).
-- Terpakai DIHITUNG dari T_PROMO_USAGE berstatus DIPAKAI (tanpa kolom).
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_PROMO;

IF OBJECT_ID('dbo.T_PROMO', 'U') IS NULL
CREATE TABLE dbo.T_PROMO (
    PROMOID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PROMOCODE VARCHAR(20) NOT NULL,
    DESCR VARCHAR(200) NULL,
    DISCTYPE VARCHAR(10) NOT NULL DEFAULT 'NOMINAL',
    DISCVALUE NUMERIC(18,2) NOT NULL DEFAULT 0,
    MAXDISC NUMERIC(18,2) NULL,
    MINPURCHASE NUMERIC(18,2) NOT NULL DEFAULT 0,
    QUOTA INT NULL,
    MAXPERBUYER INT NOT NULL DEFAULT 1,
    STARTAT DATETIME2 NULL,
    ENDAT DATETIME2 NULL,
    SCOPETYPE VARCHAR(10) NOT NULL DEFAULT 'SEMUA',
    ISACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_PROMO_CODE' AND object_id = OBJECT_ID('dbo.T_PROMO'))
CREATE UNIQUE INDEX UX_T_PROMO_CODE ON dbo.T_PROMO (PROMOCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PROMO_STATUS' AND object_id = OBJECT_ID('dbo.T_PROMO'))
CREATE INDEX IX_T_PROMO_STATUS ON dbo.T_PROMO (ISACTIVE, STARTAT);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_PROMO_PERIOD' AND object_id = OBJECT_ID('dbo.T_PROMO'))
CREATE INDEX IX_T_PROMO_PERIOD ON dbo.T_PROMO (STARTAT, ENDAT);
GO

