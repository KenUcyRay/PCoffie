-- Riwayat scan tiket (Ticket Check-in, module Ticketing).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu percobaan scan.
-- Hanya-tambah seperti T_AUDIT_LOG: tidak bisa diubah/dihapus lewat aplikasi,
-- dilindungi trigger di level database dengan cara yang sama.
-- Idempoten: CREATE/trigger/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO) karena CREATE TRIGGER harus batch tersendiri.
-- ROLLBACK (hanya development): DROP TRIGGER ...; DROP TABLE ... (lihat bawah).

IF OBJECT_ID('dbo.T_SCAN_LOG', 'U') IS NULL
CREATE TABLE dbo.T_SCAN_LOG (
    SCANID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    SCANTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    EVENTID INT NULL,
    ATTENDEEID INT NULL,
    SCANCODE VARCHAR(100) NULL,
    RESULT VARCHAR(14) NOT NULL,
    USERID INT NULL,
    USERLOGIN VARCHAR(25) NULL,
    METHOD VARCHAR(10) NULL,
    USERIP VARCHAR(45) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SCAN_LOG_TIME' AND object_id = OBJECT_ID('dbo.T_SCAN_LOG'))
CREATE INDEX IX_T_SCAN_LOG_TIME ON dbo.T_SCAN_LOG (SCANTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SCAN_LOG_EVENT' AND object_id = OBJECT_ID('dbo.T_SCAN_LOG'))
CREATE INDEX IX_T_SCAN_LOG_EVENT ON dbo.T_SCAN_LOG (EVENTID, SCANTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SCAN_LOG_RESULT' AND object_id = OBJECT_ID('dbo.T_SCAN_LOG'))
CREATE INDEX IX_T_SCAN_LOG_RESULT ON dbo.T_SCAN_LOG (RESULT, SCANTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SCAN_LOG_USER' AND object_id = OBJECT_ID('dbo.T_SCAN_LOG'))
CREATE INDEX IX_T_SCAN_LOG_USER ON dbo.T_SCAN_LOG (USERLOGIN, SCANTIME DESC);
GO

-- Perbaikan: RESULT butuh 14 char (SUDAH_DIPAKAI/DI_LUAR_JADWAL = 13 char).
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.T_SCAN_LOG') AND name = 'RESULT' AND max_length < 14)
ALTER TABLE dbo.T_SCAN_LOG ALTER COLUMN RESULT VARCHAR(14) NOT NULL;
GO

-- Tolak UPDATE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_SCAN_LOG_NOUPDATE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_SCAN_LOG_NOUPDATE ON dbo.T_SCAN_LOG INSTEAD OF UPDATE AS BEGIN RAISERROR(''T_SCAN_LOG tidak boleh diubah.'', 16, 1); END');
GO

-- Tolak DELETE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_SCAN_LOG_NODELETE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_SCAN_LOG_NODELETE ON dbo.T_SCAN_LOG INSTEAD OF DELETE AS BEGIN RAISERROR(''T_SCAN_LOG tidak boleh dihapus.'', 16, 1); END');
GO

