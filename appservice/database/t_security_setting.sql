-- Pengaturan keamanan login dan sesi (Security Center, module System).
-- Aturan: tabel baru pakai awalan T_. Satu baris = pengaturan yang berlaku.
-- Perubahan dicatat di Audit Log (before/after), jadi tanpa tabel riwayat.
-- Idempoten: CREATE hanya bila tabel belum ada; seed memakai WHERE NOT EXISTS.
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_SECURITY_SETTING;

IF OBJECT_ID('dbo.T_SECURITY_SETTING', 'U') IS NULL
CREATE TABLE dbo.T_SECURITY_SETTING (
    SETTINGID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PWDMINLEN INT NOT NULL DEFAULT 8,
    PWDREQUIREUPPER VARCHAR(3) NOT NULL DEFAULT 'YES',
    PWDREQUIREDIGIT VARCHAR(3) NOT NULL DEFAULT 'YES',
    PWDREQUIRESYMBOL VARCHAR(3) NOT NULL DEFAULT 'NO',
    PWDEXPIRYDAYS INT NOT NULL DEFAULT 0,
    MAXFAILCOUNT INT NOT NULL DEFAULT 5,
    BLOCKDURATIONMIN INT NOT NULL DEFAULT 15,
    SESIDLEMIN INT NOT NULL DEFAULT 30,
    SESMAXHOURS INT NOT NULL DEFAULT 12,
    MAXSESSION INT NOT NULL DEFAULT 3,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);

-- Data awal: satu baris pengaturan (nilai contoh, bisa diubah dari halaman
-- Security Setting). PWDEXPIRYDAYS = 0 berarti password tidak kedaluwarsa.
-- MAXSESSION = 0 berarti tanpa batas sesi per user.
INSERT INTO dbo.T_SECURITY_SETTING
    (PWDMINLEN, PWDREQUIREUPPER, PWDREQUIREDIGIT, PWDREQUIRESYMBOL,
     PWDEXPIRYDAYS, MAXFAILCOUNT, BLOCKDURATIONMIN,
     SESIDLEMIN, SESMAXHOURS, MAXSESSION, SYSCREATEUSER, SYSCREATEDATE)
SELECT 8, 'YES', 'YES', 'NO',
     0, 5, 15,
     30, 12, 3, 'SEED', GETDATE()
WHERE NOT EXISTS (SELECT 1 FROM dbo.T_SECURITY_SETTING);

