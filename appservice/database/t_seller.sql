-- Penjual merchandise (Seller Center, module Merchandise).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu toko.
-- Nonaktifkan penjual -> produknya ikut nonaktif (di kode, satu arah).
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_SELLER;

IF OBJECT_ID('dbo.T_SELLER', 'U') IS NULL
CREATE TABLE dbo.T_SELLER (
    SELLERID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    SELLERCODE VARCHAR(20) NOT NULL,
    SHOPNAME VARCHAR(100) NOT NULL,
    OWNERNAME VARCHAR(100) NOT NULL,
    PHONE VARCHAR(30) NULL,
    EMAIL VARCHAR(100) NULL,
    ADDRESS VARCHAR(500) NULL,
    ISACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_SELLER_CODE' AND object_id = OBJECT_ID('dbo.T_SELLER'))
CREATE UNIQUE INDEX UX_T_SELLER_CODE ON dbo.T_SELLER (SELLERCODE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_SELLER_SHOP' AND object_id = OBJECT_ID('dbo.T_SELLER'))
CREATE UNIQUE INDEX UX_T_SELLER_SHOP ON dbo.T_SELLER (SHOPNAME);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SELLER_ACTIVE' AND object_id = OBJECT_ID('dbo.T_SELLER'))
CREATE INDEX IX_T_SELLER_ACTIVE ON dbo.T_SELLER (ISACTIVE, SHOPNAME);
GO

