-- Tabel system log (Log Center, module System). Aturan: tabel baru pakai awalan T_.
-- Append-only: UPDATE dan DELETE ditolak trigger di bawah (bukan cuma di aplikasi).
-- Idempoten: CREATE/trigger/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO) karena CREATE TRIGGER harus batch tersendiri.
-- ROLLBACK (hanya development): DROP TRIGGER ...; DROP TABLE ... (lihat bawah).

IF OBJECT_ID('dbo.T_SYSTEM_LOG', 'U') IS NULL
CREATE TABLE dbo.T_SYSTEM_LOG (
    SYSLOGID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    LOGTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    LOGLEVEL VARCHAR(10) NOT NULL,
    LOGSOURCE VARCHAR(20) NULL,
    MESSAGE NVARCHAR(500) NULL,
    CONTEXTJSON NVARCHAR(MAX) NULL,
    STACKTRACE NVARCHAR(MAX) NULL,
    URL VARCHAR(255) NULL,
    METHOD VARCHAR(10) NULL,
    HTTPSTATUS INT NULL,
    USERID INT NULL,
    USERLOGIN VARCHAR(25) NULL,
    USERIP VARCHAR(45) NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SYSTEM_LOG_TIME' AND object_id = OBJECT_ID('dbo.T_SYSTEM_LOG'))
CREATE INDEX IX_T_SYSTEM_LOG_TIME ON dbo.T_SYSTEM_LOG (LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SYSTEM_LOG_LEVEL' AND object_id = OBJECT_ID('dbo.T_SYSTEM_LOG'))
CREATE INDEX IX_T_SYSTEM_LOG_LEVEL ON dbo.T_SYSTEM_LOG (LOGLEVEL, LOGTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_SYSTEM_LOG_SOURCE' AND object_id = OBJECT_ID('dbo.T_SYSTEM_LOG'))
CREATE INDEX IX_T_SYSTEM_LOG_SOURCE ON dbo.T_SYSTEM_LOG (LOGSOURCE, LOGTIME DESC);
GO

-- Tolak UPDATE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_SYSTEM_LOG_NOUPDATE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_SYSTEM_LOG_NOUPDATE ON dbo.T_SYSTEM_LOG INSTEAD OF UPDATE AS BEGIN RAISERROR(''T_SYSTEM_LOG tidak boleh diubah.'', 16, 1); END');
GO

-- Tolak DELETE: tabel tambah-saja.
IF OBJECT_ID('dbo.TRG_T_SYSTEM_LOG_NODELETE', 'TR') IS NULL
EXEC('CREATE TRIGGER dbo.TRG_T_SYSTEM_LOG_NODELETE ON dbo.T_SYSTEM_LOG INSTEAD OF DELETE AS BEGIN RAISERROR(''T_SYSTEM_LOG tidak boleh dihapus.'', 16, 1); END');
GO

