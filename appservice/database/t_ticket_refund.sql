-- Refund tiket (Ticket Order, module Ticketing). Aturan: tabel baru pakai awalan T_.
-- Satu tiket hanya boleh punya satu refund DIAJUKAN/DISETUJUI (unique filtered
-- index); SELESAI mencegah pengajuan lagi (dicek di kode). Transfer dana
-- dikerjakan module Finance (di sini hanya status + titik sambung).
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_TICKET_REFUND;

IF OBJECT_ID('dbo.T_TICKET_REFUND', 'U') IS NULL
CREATE TABLE dbo.T_TICKET_REFUND (
    REFUNDID BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    REFUNDNO VARCHAR(30) NOT NULL,
    TICKETID INT NOT NULL,
    EVENTID INT NOT NULL,
    NOMINAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    REASON VARCHAR(200) NULL,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'DIAJUKAN',
    DECISIONNOTE VARCHAR(200) NULL,
    REQUESTTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    REQUESTBY VARCHAR(25) NULL,
    DECISIONTIME DATETIME2 NULL,
    DECISIONBY VARCHAR(25) NULL,
    DONETIME DATETIME2 NULL,
    DONEBY VARCHAR(25) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_TICKET_REFUND_NO' AND object_id = OBJECT_ID('dbo.T_TICKET_REFUND'))
CREATE UNIQUE INDEX UX_T_TICKET_REFUND_NO ON dbo.T_TICKET_REFUND (REFUNDNO);
GO

-- Satu tiket: maksimal satu refund yang masih berjalan.
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_TICKET_REFUND_ACTIVE' AND object_id = OBJECT_ID('dbo.T_TICKET_REFUND'))
CREATE UNIQUE INDEX UX_T_TICKET_REFUND_ACTIVE ON dbo.T_TICKET_REFUND (TICKETID) WHERE STATUS IN ('DIAJUKAN', 'DISETUJUI');
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_TICKET_REFUND_TICKET' AND object_id = OBJECT_ID('dbo.T_TICKET_REFUND'))
CREATE INDEX IX_T_TICKET_REFUND_TICKET ON dbo.T_TICKET_REFUND (TICKETID, REQUESTTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_TICKET_REFUND_EVENT' AND object_id = OBJECT_ID('dbo.T_TICKET_REFUND'))
CREATE INDEX IX_T_TICKET_REFUND_EVENT ON dbo.T_TICKET_REFUND (EVENTID, REQUESTTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_TICKET_REFUND_STATUS' AND object_id = OBJECT_ID('dbo.T_TICKET_REFUND'))
CREATE INDEX IX_T_TICKET_REFUND_STATUS ON dbo.T_TICKET_REFUND (STATUS, REQUESTTIME DESC);
GO

