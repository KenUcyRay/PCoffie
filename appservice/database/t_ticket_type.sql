-- Tipe tiket per event (Event Management, module Event).
-- Aturan: tabel baru pakai awalan T_. Satu baris = satu tipe tiket.
-- Harga desimal presisi tetap (NUMERIC, bukan float); 0 = gratis.
-- Nama unik dalam satu event. Terjual DIHITUNG dari T_ATTENDEE (tanpa kolom).
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_TICKET_TYPE;

IF OBJECT_ID('dbo.T_TICKET_TYPE', 'U') IS NULL
CREATE TABLE dbo.T_TICKET_TYPE (
    TICKETTYPEID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    EVENTID INT NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    DESCR VARCHAR(500) NULL,
    PRICE NUMERIC(18,2) NOT NULL DEFAULT 0,
    QUOTA INT NOT NULL DEFAULT 0,
    MAXPERSON INT NOT NULL DEFAULT 1,
    SALESTART DATETIME2 NULL,
    SALEEND DATETIME2 NULL,
    SORTORDER INT NOT NULL DEFAULT 0,
    ISACTIVE VARCHAR(3) NOT NULL DEFAULT 'YES',
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_TICKET_TYPE_EVENTNAME' AND object_id = OBJECT_ID('dbo.T_TICKET_TYPE'))
CREATE UNIQUE INDEX UX_T_TICKET_TYPE_EVENTNAME ON dbo.T_TICKET_TYPE (EVENTID, NAME);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_TICKET_TYPE_EVENT' AND object_id = OBJECT_ID('dbo.T_TICKET_TYPE'))
CREATE INDEX IX_T_TICKET_TYPE_EVENT ON dbo.T_TICKET_TYPE (EVENTID, SORTORDER);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_TICKET_TYPE_STATUS' AND object_id = OBJECT_ID('dbo.T_TICKET_TYPE'))
CREATE INDEX IX_T_TICKET_TYPE_STATUS ON dbo.T_TICKET_TYPE (ISACTIVE, EVENTID);
GO

