-- Sesi login aktif (Security Center, module System). Aturan: tabel baru pakai awalan T_.
-- Satu baris = satu token login (SESSIONID = ID unik token, BUKAN token mentah).
-- Status berubah (AKTIF -> LOGOUT/DICABUT/KEDALUWARSA), jadi tanpa trigger
-- append-only. Tidak perlu data awal.
-- Idempoten: CREATE/index hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_USER_SESSION;

IF OBJECT_ID('dbo.T_USER_SESSION', 'U') IS NULL
CREATE TABLE dbo.T_USER_SESSION (
    SESSIONID VARCHAR(64) NOT NULL PRIMARY KEY,
    USERID INT NULL,
    USERLOGIN VARCHAR(25) NULL,
    LOGINTIME DATETIME2 NOT NULL DEFAULT GETDATE(),
    LASTACTIVE DATETIME2 NOT NULL DEFAULT GETDATE(),
    EXPIRESAT DATETIME2 NOT NULL,
    USERIP VARCHAR(45) NULL,
    USERAGENT VARCHAR(255) NULL,
    DEVICE VARCHAR(100) NULL,
    BROWSER VARCHAR(100) NULL,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'AKTIF',
    REVOKETIME DATETIME2 NULL,
    REVOKEDBY VARCHAR(25) NULL,
    REASON VARCHAR(200) NULL,
    SESIDLEMIN INT NULL,
    SESMAXHOURS INT NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_USER_SESSION_USER' AND object_id = OBJECT_ID('dbo.T_USER_SESSION'))
CREATE INDEX IX_T_USER_SESSION_USER ON dbo.T_USER_SESSION (USERLOGIN, LOGINTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_USER_SESSION_STATUS' AND object_id = OBJECT_ID('dbo.T_USER_SESSION'))
CREATE INDEX IX_T_USER_SESSION_STATUS ON dbo.T_USER_SESSION (STATUS, LOGINTIME DESC);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_USER_SESSION_ACTIVE' AND object_id = OBJECT_ID('dbo.T_USER_SESSION'))
CREATE INDEX IX_T_USER_SESSION_ACTIVE ON dbo.T_USER_SESSION (LASTACTIVE DESC);
GO

-- Perbaikan: STATUS butuh 12 char untuk nilai KEDALUWARSA (idempoten).
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('dbo.T_USER_SESSION') AND name = 'STATUS' AND max_length < 12)
ALTER TABLE dbo.T_USER_SESSION ALTER COLUMN STATUS VARCHAR(12) NOT NULL;
GO

