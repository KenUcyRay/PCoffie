-- Booking warnet: user request PENDING → operator approve → jadwal terisi.
-- Bentrok cek PCID + TGL + JAM overlap. TOTAL hitung server.
IF OBJECT_ID('dbo.T_WARNET_BOOKING', 'U') IS NULL
CREATE TABLE dbo.T_WARNET_BOOKING (
    BOOKINGID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    BOOKNO VARCHAR(20) NOT NULL,
    USERLOGIN VARCHAR(30) NOT NULL,
    PCID INT NOT NULL,
    PAKETID INT NULL,
    TGL_BOOKING DATE NOT NULL,
    JAM_MULAI TIME NOT NULL,
    JAM_SELESAI TIME NOT NULL,
    DURASI_MENIT INT NOT NULL,
    TOTAL NUMERIC(18,2) NOT NULL DEFAULT 0,
    PAYMETHOD VARCHAR(20) NOT NULL DEFAULT 'qris',
    PAYSTATUS VARCHAR(20) NOT NULL DEFAULT 'pending',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'pending',
    NOTE VARCHAR(500) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='UX_T_WARNET_BOOKING_NO' AND object_id=OBJECT_ID('dbo.T_WARNET_BOOKING'))
CREATE UNIQUE INDEX UX_T_WARNET_BOOKING_NO ON dbo.T_WARNET_BOOKING (BOOKNO);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_T_WARNET_BOOKING_PC_TGL' AND object_id=OBJECT_ID('dbo.T_WARNET_BOOKING'))
CREATE INDEX IX_T_WARNET_BOOKING_PC_TGL ON dbo.T_WARNET_BOOKING (PCID, TGL_BOOKING, STATUS);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_T_WARNET_BOOKING_USER' AND object_id=OBJECT_ID('dbo.T_WARNET_BOOKING'))
CREATE INDEX IX_T_WARNET_BOOKING_USER ON dbo.T_WARNET_BOOKING (USERLOGIN, STATUS, TGL_BOOKING);
GO
