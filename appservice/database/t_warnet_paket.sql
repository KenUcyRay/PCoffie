-- Master paket warnet (durasi fix + harga, pilih opsional ketika booking jam bebas).
-- Admin buat di Console cp_paket. Portal read-only.
-- Idempoten: CREATE hanya bila tabel belum ada. Seed pakai WHERE NOT EXISTS.
-- ROLLBACK: DROP TABLE dbo.T_WARNET_PAKET;
IF OBJECT_ID('dbo.T_WARNET_PAKET', 'U') IS NULL
CREATE TABLE dbo.T_WARNET_PAKET (
    PAKETID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    KODE VARCHAR(20) NOT NULL,
    NAMA VARCHAR(100) NOT NULL,
    ZONA VARCHAR(10) NOT NULL DEFAULT 'REGULER',
    DURASI_MENIT INT NOT NULL DEFAULT 60,
    HARGA NUMERIC(18,2) NOT NULL DEFAULT 0,
    DESKRIPSI VARCHAR(500) NULL,
    ISAKTIF VARCHAR(3) NOT NULL DEFAULT 'YES',
    SORTNO INT NOT NULL DEFAULT 0,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='UX_T_WARNET_PAKET_KODE' AND object_id=OBJECT_ID('dbo.T_WARNET_PAKET'))
CREATE UNIQUE INDEX UX_T_WARNET_PAKET_KODE ON dbo.T_WARNET_PAKET (KODE);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_T_WARNET_PAKET_AKTIF' AND object_id=OBJECT_ID('dbo.T_WARNET_PAKET'))
CREATE INDEX IX_T_WARNET_PAKET_AKTIF ON dbo.T_WARNET_PAKET (ISAKTIF, SORTNO);
GO
