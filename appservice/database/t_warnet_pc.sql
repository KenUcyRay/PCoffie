-- Master PC warnet + seat picker (pilih kursi bioskop). Status untuk cek kosong.
IF OBJECT_ID('dbo.T_WARNET_PC', 'U') IS NULL
CREATE TABLE dbo.T_WARNET_PC (
    PCID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PCNO VARCHAR(20) NOT NULL,
    ZONA VARCHAR(10) NOT NULL DEFAULT 'REGULER',
    SPEK VARCHAR(200) NULL,
    HARGA_PERJAM NUMERIC(18,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(10) NOT NULL DEFAULT 'ready',
    ISAKTIF VARCHAR(3) NOT NULL DEFAULT 'YES',
    SORTNO INT NOT NULL DEFAULT 0,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='UX_T_WARNET_PC_NO' AND object_id=OBJECT_ID('dbo.T_WARNET_PC'))
CREATE UNIQUE INDEX UX_T_WARNET_PC_NO ON dbo.T_WARNET_PC (PCNO);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name='IX_T_WARNET_PC_ZONA' AND object_id=OBJECT_ID('dbo.T_WARNET_PC'))
CREATE INDEX IX_T_WARNET_PC_ZONA ON dbo.T_WARNET_PC (ZONA, STATUS, ISAKTIF);
GO
DECLARE @i INT=1;
WHILE @i<=20 BEGIN
  DECLARE @no VARCHAR(20)=CONCAT('R-',RIGHT(CONCAT('0',@i),2));
  IF NOT EXISTS (SELECT 1 FROM dbo.T_WARNET_PC WHERE PCNO=@no)
    INSERT INTO dbo.T_WARNET_PC (PCNO,ZONA,SPEK,HARGA_PERJAM,STATUS,ISAKTIF,SORTNO,SYSCREATEUSER,SYSCREATEDATE)
    VALUES (@no,'REGULER','RTX 3060 Ti 144Hz i5',6000,'ready','YES',@i,'SEED',GETDATE());
  SET @i+=1;
END
GO
DECLARE @j INT=1;
WHILE @j<=12 BEGIN
  DECLARE @vn VARCHAR(20)=CONCAT('V-',RIGHT(CONCAT('0',@j),2));
  IF NOT EXISTS (SELECT 1 FROM dbo.T_WARNET_PC WHERE PCNO=@vn)
    INSERT INTO dbo.T_WARNET_PC (PCNO,ZONA,SPEK,HARGA_PERJAM,STATUS,ISAKTIF,SORTNO,SYSCREATEUSER,SYSCREATEDATE)
    VALUES (@vn,'VIP','RTX 4090 240Hz Pro i9',10000,'ready','YES',20+@j,'SEED',GETDATE());
  SET @j+=1;
END
GO
