-- Penarikan seller (Finance, module Finance). Aturan: T_ prefix.
-- Satu baris = satu pengajuan. Biaya + minimum disalin dari Fee Setting yang
-- berlaku saat diajukan. Dana dikunci di AVAILABLE saat diajukan
-- (WITHDRAWAL), kembali saat DITOLAK/GAGAL (WITHDRAWAL_REVERSAL).
-- Alur: DIAJUKAN -> DIPROSES -> BERHASIL; DIAJUKAN/DIPROSES -> DITOLAK/GAGAL.
-- Idempoten: CREATE/index/seed hanya bila belum ada. Jalankan per pernyataan
-- (pisahkan tiap GO).
-- ROLLBACK (jalankan manual bila perlu): DROP TABLE dbo.T_WITHDRAWAL;

IF OBJECT_ID('dbo.T_WITHDRAWAL', 'U') IS NULL
CREATE TABLE dbo.T_WITHDRAWAL (
    WITHDRAWALID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    WDNO VARCHAR(30) NOT NULL,
    SELLERID INT NOT NULL,
    BANKACCOUNTID INT NOT NULL,
    AMOUNT NUMERIC(18,2) NOT NULL DEFAULT 0,
    WITHDRAWFEE NUMERIC(18,2) NOT NULL DEFAULT 0,
    MINAPPLIED NUMERIC(18,2) NOT NULL DEFAULT 0,
    NETRECEIVED NUMERIC(18,2) NOT NULL DEFAULT 0,
    STATUS VARCHAR(12) NOT NULL DEFAULT 'DIAJUKAN',
    TRANSFERREF VARCHAR(100) NULL,
    TRANSFERDATE DATE NULL,
    PROOFIMAGE VARCHAR(255) NULL,
    REASON VARCHAR(200) NULL,
    REQUESTBY VARCHAR(25) NULL,
    REQUESTAT DATETIME2 NULL,
    PROCESSBY VARCHAR(25) NULL,
    PROCESSAT DATETIME2 NULL,
    DONEBY VARCHAR(25) NULL,
    DONEAT DATETIME2 NULL,
    IDEMPOTENCYKEY VARCHAR(64) NULL,
    SYSCREATEUSER VARCHAR(25) NULL,
    SYSCREATEDATE DATETIME2 NULL,
    SYSUPDATEUSER VARCHAR(25) NULL,
    SYSUPDATEDATE DATETIME2 NULL
);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UX_T_WITHDRAWAL_NO' AND object_id = OBJECT_ID('dbo.T_WITHDRAWAL'))
CREATE UNIQUE INDEX UX_T_WITHDRAWAL_NO ON dbo.T_WITHDRAWAL (WDNO);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_WITHDRAWAL_SELLER' AND object_id = OBJECT_ID('dbo.T_WITHDRAWAL'))
CREATE INDEX IX_T_WITHDRAWAL_SELLER ON dbo.T_WITHDRAWAL (SELLERID);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_WITHDRAWAL_STATUS' AND object_id = OBJECT_ID('dbo.T_WITHDRAWAL'))
CREATE INDEX IX_T_WITHDRAWAL_STATUS ON dbo.T_WITHDRAWAL (STATUS);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_T_WITHDRAWAL_TIME' AND object_id = OBJECT_ID('dbo.T_WITHDRAWAL'))
CREATE INDEX IX_T_WITHDRAWAL_TIME ON dbo.T_WITHDRAWAL (REQUESTAT DESC);
GO

